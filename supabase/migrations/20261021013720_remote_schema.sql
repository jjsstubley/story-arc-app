CREATE OR REPLACE FUNCTION "public"."find_similar_queries"("search_prompt" "text", "user_id" "uuid", "similarity_threshold" real DEFAULT 0.3) RETURNS TABLE("id" "uuid", "created_at" timestamp with time zone, "prompt" "text", "context" "jsonb", "generated_by" "uuid", "similarity" real)
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
BEGIN
  RETURN QUERY
  SELECT 
    aq.id,
    aq.created_at,
    aq.prompt,
    aq.context,
    aq.generated_by,
    similarity(aq.prompt, search_prompt) as similarity
  FROM ai_queries aq
  WHERE 
    aq.generated_by = user_id
    AND similarity(aq.prompt, search_prompt) >= similarity_threshold
  ORDER BY similarity DESC, created_at DESC
  LIMIT 1;
END;
$$;


